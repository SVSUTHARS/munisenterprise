/* =========================================
   LOAD SERVICES
========================================= */

document.addEventListener("DOMContentLoaded", function () {

    const servicesList =
        document.getElementById("servicesList");

    if (!servicesList) return;


    services.forEach(function (service, index) {

        const card =
            document.createElement("div");

        card.className = "service";


        card.innerHTML = `

            <div class="service-icon">
                ${service.icon}
            </div>

            <h3>
                ${service.title}
            </h3>

            <p>
                ${service.english}
            </p>

        `;


        /* CLICK */

        card.addEventListener("click", function () {

            openServiceDetails(index);

        });


        servicesList.appendChild(card);

    });


    /* YEAR */

    const year =
        document.getElementById("year");

    if (year) {

        year.textContent =
            new Date().getFullYear();

    }

});


/* =========================================
   OPEN DETAILS
========================================= */

function openServiceDetails(index) {

    const service =
        services[index];


    document.getElementById(
        "serviceModalIcon"
    ).textContent =
        service.icon;


    document.getElementById(
        "serviceModalTitle"
    ).textContent =
        service.title;


    document.getElementById(
        "serviceModalEnglish"
    ).textContent =
        service.english;


    const list =
        document.getElementById(
            "serviceModalList"
        );


    list.innerHTML = "";


    service.details.forEach(function (detail) {

        const li =
            document.createElement("li");

        li.textContent =
            detail;

        list.appendChild(li);

    });


    document.getElementById(
        "serviceModal"
    ).style.display =
        "flex";


    document.body.style.overflow =
        "hidden";

}


/* =========================================
   CLOSE DETAILS
========================================= */

function closeServiceDetails() {

    document.getElementById(
        "serviceModal"
    ).style.display =
        "none";


    document.body.style.overflow =
        "auto";

}


/* =========================================
   CLICK OUTSIDE POPUP
========================================= */

document.addEventListener("click", function (event) {

    const modal =
        document.getElementById("serviceModal");


    if (
        event.target === modal
    ) {

        closeServiceDetails();

    }

});


/* =========================================
   ESC KEY
========================================= */

document.addEventListener("keydown", function (event) {

    if (event.key === "Escape") {

        closeServiceDetails();

    }

});


/* =========================================
   MOBILE MENU
========================================= */

function toggleMenu() {

    const nav =
        document.getElementById("nav");

    nav.classList.toggle("active");

}